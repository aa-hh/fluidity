import AppKit

/// `Pasteboard` over `NSPasteboard.general`, offering pasted text through `NSPasteboardItemDataProvider`.
@MainActor
public final class NSPasteboardPasteboard: Pasteboard {
    private static let marker = NSPasteboard.PasteboardType("com.fluidity.app.pasted-text")
    /// Ask clipboard managers to skip our item, so their reads are not mistaken for a paste landing.
    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
    ]

    private let pasteboard: NSPasteboard
    /// Held here because the item's hold on its provider is not documented as strong.
    private var provider: DelayedTextProvider?

    public init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public func snapshot() -> PasteboardSnapshot {
        PasteboardSnapshot(items: (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { PasteboardSnapshot.Representation(type: type.rawValue, data: $0) }
            }
        })
    }

    public func writeDelayed(_ text: String, onRequest: @escaping @Sendable () -> Void) -> Bool {
        pasteboard.clearContents()
        let provider = DelayedTextProvider(text: text, onRequest: onRequest)
        self.provider = provider
        let item = NSPasteboardItem()
        guard item.setDataProvider(provider, forTypes: [.string]) else { return false }
        for type in [Self.marker] + Self.skipTypes {
            item.setData(Data(), forType: type)
        }
        return pasteboard.writeObjects([item])
    }

    public var changeCount: Int { pasteboard.changeCount }

    public var holdsOurItem: Bool { pasteboard.types?.contains(Self.marker) ?? false }

    public func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        provider = nil
        let items = snapshot.items.map { representations in
            let item = NSPasteboardItem()
            for representation in representations {
                item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }
}

private final class DelayedTextProvider: NSObject, NSPasteboardItemDataProvider, Sendable {
    private let text: String
    private let onRequest: @Sendable () -> Void

    init(text: String, onRequest: @escaping @Sendable () -> Void) {
        self.text = text
        self.onRequest = onRequest
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        onRequest()
    }
}
